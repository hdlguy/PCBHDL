#!/usr/bin/env python3
"""Regenerate the Python parser from pcbhdl/grammar/Phdl.g4.

Needs Java and the ANTLR 4.13.2 tool jar. The jar is downloaded into
tools/ on first use. The generated files are committed so that users of
pcbhdl do not need Java.
"""
import pathlib
import subprocess
import sys
import urllib.request

ANTLR_VERSION = "4.13.2"
ROOT = pathlib.Path(__file__).resolve().parent.parent
JAR = ROOT / "tools" / f"antlr-{ANTLR_VERSION}-complete.jar"
GRAMMAR_DIR = ROOT / "pcbhdl" / "grammar"
OUT_DIR = ROOT / "pcbhdl" / "_generated"


def main() -> int:
    if not JAR.exists():
        url = f"https://www.antlr.org/download/antlr-{ANTLR_VERSION}-complete.jar"
        print(f"downloading {url}")
        urllib.request.urlretrieve(url, JAR)
    OUT_DIR.mkdir(exist_ok=True)
    (OUT_DIR / "__init__.py").write_text('"""Generated by ANTLR from pcbhdl/grammar/Phdl.g4. Do not edit."""\n')
    cmd = ["java", "-jar", str(JAR), "-Dlanguage=Python3", "-visitor", "-no-listener",
           "-Xexact-output-dir", "-o", str(OUT_DIR), str(GRAMMAR_DIR / "Phdl.g4")]
    return subprocess.call(cmd)


if __name__ == "__main__":
    sys.exit(main())
